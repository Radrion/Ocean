# Function to load processed alerts into DuckDB
def load_into_duckdb(processed_alerts):
    '''Load the processed alerts into DuckDB for analysis
    processed_alerts: A list of dictionaries containing the processed alert information'''
    
    df = pd.DataFrame(processed_alerts)
    conn = duckdb.connect(database=':memory:')
    conn.execute("CREATE TABLE threats AS SELECT * FROM df")
    print("threats loaded into DuckDB successfully!")
    return conn


# Function to get the schema of the threats table
def get_schema(conn):
    connect = conn.execute(f"DESCRIBE threats").fetchdf()
    return connect.to_string()


# Function to translate natural language queries into SQL using Ollama
def sql_translate(user_query, schema):
    '''Translate a natural language query into SQL based on the provided schema
    user_query: The natural language query from the user
    schema: The schema of the threats table in DuckDB'''
    messages = ollama.chat(model = "qwen2.5", messages = [
        {"role": "system", "content": f"You are a helpful assistant that translates natural language queries into SQL. The schema of the threats table is: {schema}"},
        {"role": "user", "content": user_query}
    ])
    response = messages['message']['content']
    return response

# Function to clean SQL query
def sql_cleaner(sql_query):
    '''Clean the generated SQL query to ensure it is safe and valid
    sql_query: The output generated by Qwen2.5'''
    # Basic cleaning steps (this can be expanded with more robust checks)
    match = re.search(r'```sql\s*(.*?)\s*```', sql_query, re.DOTALL)
    if match:
        pristine_query = match.group(1).strip()
        return pristine_query
    return sql_query.strip()


# Function to execute the cleaned SQL query against the DuckDB database
def run_query(conn, sql_query):
    '''Execute the cleaned SQL query against the DuckDB database
    conn: The DuckDB connection object
    sql_query: The cleaned SQL query to execute'''
    runner =conn.execute(sql_query)
    result = runner.fetchdf()
    return result

def visualizer(df):
    '''Visualize the query results using a simple bar chart
    df: The DataFrame containing the query results'''
    if df.empty:
        print("No data to visualize.")
        return
    rows, cols = df.shape
    if rows == 1 and cols == 1:
        print("Single value result:", df.iloc[0, 0])
    elif cols == 2 and pd.api.types.is_numeric_dtype(df.iloc[:, 1]):
        plt.bar(df.iloc[:, 0], df.iloc[:, 1])
        plt.xlabel(df.columns[0])
        plt.ylabel(df.columns[1])
        plt.title("Query Results Visualization")
        plt.xticks(rotation=45)
        plt.tight_layout()
        plt.show()
    elif 'timestamp' in df.columns:
        df['timestamp'] = pd.to_datetime(df['timestamp'])
        df.set_index('timestamp', inplace=True)
        df.plot(kind='line')
        plt.xlabel("Time")
        plt.ylabel("Values")
        plt.title("Time Series Visualization")
        plt.xticks(rotation=45)
        plt.tight_layout()
        plt.show()
    else:
        print("Query Result:\n", df)
