# Function to authenticate and get a token
def get_wazuh_token(base_url, username, password):
    '''Authenticate with the Wazuh API and return the token
    base_url: The base URL of the Wazuh API (e.g., https://your-wazuh-manager:55000)
    username: The Wazuh API username
    password: The Wazuh API password'''
    response = requests.post(
        f"{base_url}/security/user/authenticate",
        auth=(username, password),
        verify=False
    )
    if response.status_code == 200:
        token = response.json()['data']['token']
        print("Authenticated successfully!")
        return token
    else:
        print(f"Authentication failed: {response.json()}")
        return None

def get_agents(base_url, token):
    '''Get the list of monitored machines (agents) from the Wazuh API
    base_url: The base URL of the Wazuh API
    token: The authentication token'''
    headers = {"Authorization": f"Bearer {token}"}
    response = requests.get(
        f"{base_url}/agents",
        headers=headers,
        verify=False
    )
    print("Status code:", response.status_code)
    print("Response:", response.json())
    return response.json()

